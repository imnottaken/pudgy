import type { Report } from "./analyze.js";
import { formatBytes } from "./format.js";

/** Hidden marker so the action can find and update its own comment. */
export const COMMENT_MARKER = "<!-- pudgy-comment -->";

/** Ignore per-dependency changes smaller than this; they are noise in a PR. */
const MIN_CHANGE = 50 * 1024;

const md = (s: string): string => s.replace(/[|`\\]/g, "\\$&");

function signed(delta: number): string {
  if (delta === 0) return "no change";
  return `${delta > 0 ? "+" : "−"}${formatBytes(Math.abs(delta))}`;
}

function plural(n: number, word: string): string {
  return `${n} ${word}${n === 1 ? "" : "s"}`;
}

export function isReport(value: unknown): value is Report {
  const r = value as Partial<Report> | null;
  return (
    typeof r === "object" &&
    r !== null &&
    typeof r.totalSize === "number" &&
    typeof r.packageCount === "number" &&
    Array.isArray(r.direct) &&
    Array.isArray(r.swaps)
  );
}

interface Change {
  name: string;
  before: number | undefined;
  after: number | undefined;
}

function dependencyChanges(head: Report, base: Report): Change[] {
  const before = new Map(base.direct.map((d) => [d.name, d.exclusive]));
  const after = new Map(head.direct.map((d) => [d.name, d.exclusive]));
  const changes: Change[] = [];
  for (const name of new Set([...before.keys(), ...after.keys()])) {
    const b = before.get(name);
    const a = after.get(name);
    if (Math.abs((a ?? 0) - (b ?? 0)) < MIN_CHANGE) continue;
    changes.push({ name, before: b, after: a });
  }
  return changes.sort((x, y) => Math.abs((y.after ?? 0) - (y.before ?? 0)) - Math.abs((x.after ?? 0) - (x.before ?? 0)));
}

/** Markdown for a pull request comment. Pass `base` to include before/after. */
export function renderComment(head: Report, base?: Report): string {
  const out: string[] = [COMMENT_MARKER, "## pudgy — dependency weight", ""];

  let summary = `**${md(head.project.name)}: ${formatBytes(head.totalSize)}** across ${plural(head.packageCount, "package")}`;
  if (base) {
    const bytes = head.totalSize - base.totalSize;
    const pkgs = head.packageCount - base.packageCount;
    summary +=
      bytes === 0 && pkgs === 0
        ? " — no change from the base branch."
        : ` — ${signed(bytes)}, ${pkgs >= 0 ? "+" : "−"}${plural(Math.abs(pkgs), "package")} compared with the base branch.`;
  }
  out.push(summary, "");

  if (base) {
    const changes = dependencyChanges(head, base).slice(0, 10);
    if (changes.length > 0) {
      out.push("### Dependency changes", "");
      out.push("| Dependency | Before | After | Change |", "| --- | ---: | ---: | ---: |");
      for (const c of changes) {
        const note = c.before === undefined ? " (new)" : c.after === undefined ? " (removed)" : "";
        out.push(
          `| \`${md(c.name)}\`${note} | ${c.before === undefined ? "–" : formatBytes(c.before)} | ` +
            `${c.after === undefined ? "–" : formatBytes(c.after)} | ${signed((c.after ?? 0) - (c.before ?? 0))} |`,
        );
      }
      out.push("", "<sub>Sizes count only what no other dependency also needs, so they show what each one adds or frees.</sub>", "");
    }
  }

  const biggest = head.direct.slice(0, 5);
  if (biggest.length > 0) {
    out.push("<details><summary>Heaviest dependencies</summary>", "");
    out.push("| Dependency | Freed if removed | Packages |", "| --- | ---: | ---: |");
    for (const d of biggest) {
      out.push(`| \`${md(d.name)}\`${d.dev ? " (dev)" : ""} | ${formatBytes(d.exclusive)} | ${d.exclusivePackages} |`);
    }
    out.push("", "</details>", "");
  }

  const direct = head.swaps.filter((s) => s.direct).slice(0, 5);
  if (direct.length > 0) {
    out.push("### Swap ideas", "");
    for (const s of direct) {
      out.push(`- \`${md(s.name)}\` → ${md(s.alt)}${s.kind === "built-in" ? " (built in)" : ""}: about ${formatBytes(s.saves)} smaller. ${md(s.note)}`);
    }
    out.push("");
  }

  out.push("<sub>Generated by [pudgy](https://github.com/imnottaken/pudgy). Sizes are install size on disk.</sub>", "");
  return out.join("\n");
}
